# E1 operational simulation (sales / receipts / adjustments)
# ------------------------------------------------------------------
# Default length of the forward simulation (days after SIMULATION_DATE).
E1_SIMULATION_DAYS = FORECAST_HORIZON_DAYS

# Requested sales for simulated day d = units_sold on the same day one year
# earlier (d - 365) in the derived sales history, scaled per item:
#   "demand_calibrated": x (mean demand_qty / mean units_sold) for that item.
#       sales.csv volumes are ~2.8x demand.csv, while stock and thresholds
#       are sized to demand; calibration keeps the sales day-to-day pattern
#       (weekday, price/promo dips) at the demand scale.
#   "raw": units_sold unchanged (stress test; most items stock out within days).
