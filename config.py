# Replenishment during the E1 operational simulation (python main.py simulate):
#   "plan+reorder_point" (DEFAULT): execute the Phase 9 P1 plan made on
#       SIMULATION_DATE, and during the simulation apply the E1 reorder-point
#       rule each day: if usable + on-order <= min_threshold, order
#       ceil(min_threshold + avg_daily_demand x lead_time) - (usable + on-order),
#       received after lead_time_days. These are OPERATIONAL reorders labelled
#       E1_OPERATIONAL_REORDER. They are not part of the P1 recommendation and
#       never change the Phase 9 decision engine.
#   "plan-only": execute only the P1 plan (comparison/testing). "plan" is an alias.
E1_REPLENISHMENT_POLICY = "plan+reorder_point"

# SIMULATION ASSUMPTION, not source data: batch expiry for supplier receipts.
