# ------------------------------------------------------------------
# Simulated timeline
# ------------------------------------------------------------------
# The system behaves as if "today" is SIMULATION_DATE:
#   history  = demand on or before SIMULATION_DATE
#              (2025-10-01 .. 2026-09-30 in the date-shifted simulation copy)
#   forecast = the FORECAST_HORIZON_DAYS days after SIMULATION_DATE
#              (2026-10-01 .. 2026-10-30)
# Ayush's source demand (2025-09-23 .. 2026-09-22) is shifted by a constant
# number of days so that it ends on SIMULATION_DATE (see database/simulation_data.py).

SIMULATION_DATE = "2026-09-30"
FORECAST_HORIZON_DAYS = 30


def simulation_timestamp() -> pd.Timestamp:
    """SIMULATION_DATE as a normalised pandas Timestamp (raises on a bad value)."""
    ts = pd.Timestamp(SIMULATION_DATE)
    if pd.isna(ts):
        raise ValueError(f"Invalid SIMULATION_DATE: {SIMULATION_DATE!r}")
    return ts.normalize()


